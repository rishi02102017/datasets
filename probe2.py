from datasets import *
def T(name, fn):
    try:
        r = fn()
        print(f"[{name}] OK -> {r!r}"[:700])
    except Exception as e:
        print(f"[{name}] EXC {type(e).__name__}: {e}"[:700])
k = [1,1,1,2,2,3,3,3,3,4]
d = Dataset.from_dict({"k": k, "v": list(range(10))})
it = d.to_iterable_dataset()
it2 = d.to_iterable_dataset(num_shards=2)
T("ds_bycol", lambda: d.batch(by_column="k")["v"])
T("ds_bycol_bs2", lambda: d.batch(by_column="k", batch_size=2)["v"])
T("ds_bycol_bs1", lambda: d.batch(by_column="k", batch_size=1)["v"])
T("ds_bycol_bs3_drop", lambda: d.batch(by_column="k", batch_size=3, drop_last_batch=True)["v"])
T("ds_bycol_shuffled", lambda: d.shuffle(seed=0).batch(by_column="k", batch_size=2)["k"])
T("ds_bycol_twice", lambda: (d.batch(by_column="k", batch_size=2)["v"], d.batch(by_column="k", batch_size=2)["v"]))
T("ds_bycol_empty", lambda: d.select([]).batch(by_column="k").num_rows)
T("ds_bycol_nulls", lambda: Dataset.from_dict({"k":[None,None,1,1,None], "v":[0,1,2,3,4]}).batch(by_column="k", batch_size=2)["v"])
T("ds_bycol_multi", lambda: Dataset.from_dict({"a":[1,1,1,2],"b":[1,1,2,2],"v":[0,1,2,3]}).batch(by_column=["a","b"], batch_size=1)["v"])
T("ds_bycol_format_np", lambda: d.with_format("numpy").batch(by_column="k", batch_size=2)[0])
T("ds_batch_fmt", lambda: d.with_format("numpy").batch(batch_size=4).format)
T("ds_batch_empty", lambda: d.select([]).batch(batch_size=4).num_rows)
T("ds_batch_numproc", lambda: d.batch(batch_size=3, num_proc=2)["v"])
T("it_bycol", lambda: [x["v"] for x in it.batch(by_column="k")])
T("it_bycol_bs2", lambda: [x["v"] for x in it.batch(by_column="k", batch_size=2)])
T("it_bycol_bs2_shards", lambda: [x["v"] for x in it2.batch(by_column="k", batch_size=2)])
T("it_bycol_drop", lambda: [x["v"] for x in it.batch(by_column="k", batch_size=3, drop_last_batch=True)])
T("it_bycol_nulls", lambda: [x["v"] for x in Dataset.from_dict({"k":[None,None,1,1,None], "v":[0,1,2,3,4]}).to_iterable_dataset().batch(by_column="k", batch_size=2)])
T("it_bycol_reiter", lambda: (lambda b: ([x["v"] for x in b], [x["v"] for x in b]))(it.batch(by_column="k", batch_size=2)))
T("it_bycol_gen", lambda: [x["v"] for x in IterableDataset.from_generator(lambda: ({"k": a, "v": i} for i, a in enumerate(k))).batch(by_column="k", batch_size=2)])
T("it_bycol_gen_nofeat", lambda: [x for x in IterableDataset.from_generator(lambda: ({"k": a, "v": i} for i, a in enumerate(k))).batch(by_column="k", batch_size=2)][:2])
T("it_bycol_take", lambda: [x["v"] for x in it.batch(by_column="k", batch_size=2).take(2)])
T("it_bycol_state", lambda: (lambda b: (b.load_state_dict((lambda s: s)(next(iter([0])) and None or b.state_dict())), [x["v"] for x in b]))(it.batch(by_column="k", batch_size=2)))
T("it_bycol_fmt_np", lambda: [x["v"] for x in it.with_format("numpy").batch(by_column="k", batch_size=2)])
T("it_bycol_fmt_arrow", lambda: [x for x in it.with_format("arrow").batch(by_column="k", batch_size=2)][0])
T("it_batch_fmt_np", lambda: [x["v"] for x in it.with_format("numpy").batch(batch_size=4)])
T("it_batch_fmt_pd", lambda: [x for x in it.with_format("pandas").batch(batch_size=4)][0])
T("it_batch_gen_fmt_np", lambda: [x["v"] for x in IterableDataset.from_generator(lambda: ({"k": a, "v": i} for i, a in enumerate(k))).with_format("numpy").batch(batch_size=4)])
T("it_batch_features", lambda: it.batch(batch_size=4).features)
T("it_bycol_features", lambda: it.batch(by_column="k").features)
